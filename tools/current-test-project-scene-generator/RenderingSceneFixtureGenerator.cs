        SceneEntityAsset Entity(string id, string name, float3 position, float3 scale, SceneComponentAssetRecord[] components) {
            return new SceneEntityAsset {
                Id = StableEntityId(id),
                Name = name,
                LocalPosition = position,
                LocalScale = scale,
                LocalOrientation = float4.Identity,
                Components = components,
                Children = Array.Empty<SceneEntityAsset>()
            };
        }

        static uint StableEntityId(string value) {
            if (string.IsNullOrWhiteSpace(value)) {
                throw new ArgumentException("Entity id must be provided.", nameof(value));
            }

            uint hash = 2166136261u;
            for (int index = 0; index < value.Length; index++) {
                hash ^= value[index];
                hash *= 16777619u;
            }

            return hash == 0 ? 1u : hash;
        }

