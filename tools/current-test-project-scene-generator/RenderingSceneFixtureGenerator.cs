        /// <summary>
        /// Creates one current standard-shader material definition for the rendering catalog.
        /// </summary>
        /// <param name="materialId">Stable material importer id.</param>
        /// <param name="alphaMode">Standard shader alpha-mode value.</param>
        /// <param name="doubleSided">Whether back-face culling is disabled.</param>
        /// <param name="identitySeed">Stable identity seed for the authored settings document.</param>
        /// <returns>Current generated material definition.</returns>
        static GeneratedMaterialAssetDefinition CreateMaterialDefinition(
            string materialId,
            string alphaMode,
            bool doubleSided,
            string identitySeed) {
            GeneratedMaterialAssetDefinition definition = new GeneratedMaterialAssetDefinition {
                MaterialAsset = new ShaderMaterialAsset {
                    Id = materialId,
                    AuthoringAssetId = CreateStableAuthoringAssetId(identitySeed),
                    FormerAuthoringAssetIds = Array.Empty<string>(),
                    RenderState = new MaterialRenderState {
                        BlendMode = string.Equals(alphaMode, "alpha-blend", StringComparison.Ordinal)
                            ? MaterialBlendMode.AlphaBlend
                            : MaterialBlendMode.Opaque,
                        CullMode = doubleSided ? MaterialCullMode.None : MaterialCullMode.Back,
                        DepthTestEnabled = true,
                        DepthWriteEnabled = !string.Equals(alphaMode, "alpha-blend", StringComparison.Ordinal)
                    },
                    CastsShadows = true,
                    ReceivesShadows = true
                }
            };
            GeneratedMaterialPlatformDefinition platform = definition.GetOrCreatePlatform("windows");
            platform.SchemaId = "standard-shader";
            platform.SetFieldValue("use-custom-shader", "false");
            platform.SetFieldValue("shader-asset-id", "ForwardStandardShader");
            platform.SetFieldValue("alpha-mode", alphaMode);
            platform.SetFieldValue("double-sided", doubleSided ? "true" : "false");
            platform.SetFieldValue("casts-shadow", "true");
            platform.SetFieldValue("receives-shadow", "true");
            platform.SetFieldValue("base-color", "#FFFFFFFF");
            return definition;
        }

        /// <summary>
        /// Derives one stable lower-case hexadecimal authoring identity from a committed logical path.
        /// </summary>
        /// <param name="logicalPath">Stable logical path used as the identity seed.</param>
        /// <returns>32-character lower-case hexadecimal authoring identity.</returns>
        static string CreateStableAuthoringAssetId(string logicalPath) {
            if (string.IsNullOrWhiteSpace(logicalPath)) {
                throw new ArgumentException("Logical path must be provided.", nameof(logicalPath));
            }

            byte[] digest = SHA256.HashData(Encoding.UTF8.GetBytes("helengine.current-test-project-rendering|" + logicalPath));
            return Convert.ToHexString(digest, 0, 16).ToLowerInvariant();
        }

        static SceneAssetReference FileReference(string projectRootPath, string relativePath) {
            string fullPath = Path.Combine(projectRootPath, "assets", relativePath.Replace('/', Path.DirectorySeparatorChar));
            byte[] content = File.ReadAllBytes(fullPath);
            byte[] digest = System.Security.Cryptography.SHA256.HashData(content);
            string hex = Convert.ToHexString(digest).ToLowerInvariant();
            return SceneAssetReferenceFactory.CreateFileSystemReference(hex.Substring(0, 32), relativePath, "sha256:" + hex);
        }
    }
