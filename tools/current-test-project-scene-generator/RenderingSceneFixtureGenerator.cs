        SceneAsset BuildScene(string id, SceneEntityAsset camera, SceneEntityAsset[] meshes, SceneAssetReference[] references) {
            SceneEntityAsset[] entities = new SceneEntityAsset[meshes.Length + 1];
            entities[0] = camera;
            Array.Copy(meshes, 0, entities, 1, meshes.Length);
            return BuildScene(id, entities, references);
        }

        SceneAsset BuildScene(string id, SceneEntityAsset[] entities, SceneAssetReference[] references) {
            return new SceneAsset {
                Id = SceneRootRelativePath + "/" + id + SceneAsset.FileExtension,
                AssetReferences = references,
                RootEntities = entities,
                SceneSettings = new SceneSettingsAsset()
            };
        }

        SceneEntityAsset[] Meshes(string prefix, SceneAssetReference model, SceneAssetReference material, int count) {
            SceneEntityAsset[] meshes = new SceneEntityAsset[count];
            for (int index = 0; index < count; index++) {
                meshes[index] = Mesh(prefix + "-mesh-" + index, prefix + "Mesh" + index, new float3(index * 3f - 3f, 0f, index), new float3(2f, 2f, 2f), model, material);
            }
            return meshes;
        }

        void AddMarkers(List<SceneEntityAsset> entities, string prefix, SceneAssetReference model, SceneAssetReference material, float distance, float offset, float scale, int count = 18) {
            for (int index = 0; index < count; index++) {
                float angle = (float)(index * Math.PI * 2d / count);
                entities.Add(Mesh(prefix + "-" + index, prefix + "" + index, new float3((float)Math.Cos(angle) * distance, index % 3 * offset - offset, (float)Math.Sin(angle) * distance), new float3(scale, scale, scale), model, material));
            }
        }

        SceneEntityAsset Camera(float3 position, string id = "camera", string name = "Camera", string scriptTypeId = null, DepthPrepassMode depthPrepassMode = DepthPrepassMode.Auto) {
            List<SceneComponentAssetRecord> records = new List<SceneComponentAssetRecord> { Component(CameraTypeId, CameraPayload(depthPrepassMode)) };
            if (!string.IsNullOrWhiteSpace(scriptTypeId)) {
                records.Add(Component(scriptTypeId, ScriptPayload()));
            }
            return Entity(id, name, position, float3.One, records.ToArray());
        }

