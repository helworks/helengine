            for (int index = 0; index < Ps2BasisMaterialDefinitions.Length; index++) {
                (string name, string baseColor) = Ps2BasisMaterialDefinitions[index];
                string materialRelativePath = MaterialRootRelativePath + "/ps2_basis_light_test/" + name + ".hasset";
                string materialId = MaterialRootRelativePath + ".ps2_basis_light_test." + name;
                GeneratedMaterialAssetDefinition definition = new GeneratedMaterialAssetDefinition {
                    MaterialAsset = new ShaderMaterialAsset {
                        Id = materialId,
                        AuthoringAssetId = CreateStableAuthoringAssetId(materialRelativePath),
                        FormerAuthoringAssetIds = Array.Empty<string>(),
                        RenderState = new MaterialRenderState {
                            BlendMode = MaterialBlendMode.Opaque,
                            CullMode = MaterialCullMode.Back,
                            DepthTestEnabled = true,
                            DepthWriteEnabled = true
                        },
                        CastsShadows = true,
                        ReceivesShadows = true
                    }
                };

                GeneratedMaterialPlatformDefinition windows = definition.GetOrCreatePlatform("windows");
                windows.SchemaId = "standard-shader";
                windows.SetFieldValue("use-custom-shader", "false");
                windows.SetFieldValue("texture-id", string.Empty);
                windows.SetFieldValue("casts-shadow", "true");
                windows.SetFieldValue("receives-shadow", "true");
                windows.SetFieldValue("base-color", baseColor);

                GeneratedMaterialPlatformDefinition ps2 = definition.GetOrCreatePlatform("ps2");
                ps2.SchemaId = "ps2-simple-lit-textured";
                ps2.SetFieldValue("alpha-mode", "opaque");
                ps2.SetFieldValue("double-sided", "false");
                ps2.SetFieldValue("cast-shadows", "true");
                ps2.SetFieldValue("vertex-color-mode", "ignore");
                ps2.SetFieldValue("base-color", baseColor);

                MaterialWriter.WriteMaterial(projectRootPath, materialRelativePath, definition);
            }
        }

