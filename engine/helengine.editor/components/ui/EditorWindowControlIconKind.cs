namespace helengine.editor {
    /// <summary>Identifies the vector glyph used by a host window control.</summary>
    public enum EditorWindowControlIconKind {
        /// <summary>Horizontal line used to minimize the host window.</summary>
        Minimize,
        /// <summary>Single window outline used to maximize the host window.</summary>
        Maximize,
        /// <summary>Overlapping window outlines used to restore the host window.</summary>
        Restore,
        /// <summary>Cross used to close the host window.</summary>
        Close
    }
}
