namespace helengine.player {
    /// <summary>
    /// Names the engine pad stick axes the keyboard-emulated pad can deflect.
    /// </summary>
    public enum PlayerGamepadAxis {
        /// <summary>Left stick horizontal axis; negative is left.</summary>
        LeftStickX = 0,
        /// <summary>Left stick vertical axis; negative is up, as on the PS2 pad.</summary>
        LeftStickY = 1,
        /// <summary>Right stick horizontal axis; negative is left.</summary>
        RightStickX = 2,
        /// <summary>Right stick vertical axis; negative is up, as on the PS2 pad.</summary>
        RightStickY = 3
    }
}
