namespace helengine {
    /// <summary>Identifies the IEEE storage or arithmetic widths available to build numeric policies.</summary>
    public enum NumericPrecisionBits {
        /// <summary>IEEE binary16 with eleven significant binary digits.</summary>
        Binary16 = 16,
        /// <summary>IEEE binary32 with twenty-four significant binary digits.</summary>
        Binary32 = 32,
        /// <summary>IEEE binary64 with fifty-three significant binary digits.</summary>
        Binary64 = 64
    }
}
