namespace helengine {
    /// <summary>Semantic system-font roles whose preferred sizes follow the host text-size environment.</summary>
    public enum SystemTextRole {
        /// <summary>Primary page heading.</summary>
        LargeTitle,
        /// <summary>Section heading.</summary>
        Title,
        /// <summary>Emphasized control or row heading.</summary>
        Headline,
        /// <summary>Primary reading text.</summary>
        Body,
        /// <summary>Secondary reading text.</summary>
        Callout,
        /// <summary>Supporting metadata.</summary>
        Footnote,
        /// <summary>Compact supporting label.</summary>
        Caption
    }
}
