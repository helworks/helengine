    public enum ScrollOrientation {
        /// <summary>
        /// Scrolls content vertically through the viewport.
        /// </summary>
        Vertical,

        /// <summary>
        /// Scrolls content horizontally through the viewport.
        /// </summary>
        Horizontal
    }
}
